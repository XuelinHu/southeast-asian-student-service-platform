import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const source = await readFile(path.join(root, 'database', 'schema.sql'), 'utf8');

function findMatchingParen(sql, start) {
  let depth = 0;
  let quote = null;
  for (let index = start; index < sql.length; index += 1) {
    const char = sql[index];
    if (quote) {
      if (char === quote && sql[index + 1] === quote) index += 1;
      else if (char === quote && sql[index - 1] !== '\\') quote = null;
      continue;
    }
    if (char === "'" || char === '`') { quote = char; continue; }
    if (char === '(') depth += 1;
    if (char === ')' && --depth === 0) return index;
  }
  throw new Error('Unclosed parenthesis in MySQL schema.');
}

function splitItems(body) {
  const items = [];
  let start = 0;
  let depth = 0;
  let quote = null;
  for (let index = 0; index < body.length; index += 1) {
    const char = body[index];
    if (quote) {
      if (char === quote && body[index + 1] === quote) index += 1;
      else if (char === quote && body[index - 1] !== '\\') quote = null;
      continue;
    }
    if (char === "'" || char === '`') { quote = char; continue; }
    if (char === '(') depth += 1;
    if (char === ')') depth -= 1;
    if (char === ',' && depth === 0) {
      items.push(body.slice(start, index).trim());
      start = index + 1;
    }
  }
  if (body.slice(start).trim()) items.push(body.slice(start).trim());
  return items;
}

function readSqlStringList(value) {
  const result = [];
  let current = '';
  let quote = false;
  for (let index = 0; index < value.length; index += 1) {
    const char = value[index];
    if (quote && char === "'" && value[index + 1] === "'") { current += "''"; index += 1; continue; }
    if (char === "'") { quote = !quote; current += char; continue; }
    if (char === ',' && !quote) { result.push(current.trim()); current = ''; continue; }
    current += char;
  }
  if (current.trim()) result.push(current.trim());
  return result;
}

function quoteSql(value) { return `'${String(value).replaceAll("'", "''")}'`; }

const tables = [];
const seeds = [];
const tableStartPattern = /CREATE TABLE IF NOT EXISTS\s+`?(\w+)`?\s*\(/gi;
let match;
let lastEnd = 0;
while ((match = tableStartPattern.exec(source))) {
  const [, tableName] = match;
  const openIndex = source.indexOf('(', match.index);
  const closeIndex = findMatchingParen(source, openIndex);
  const semicolon = source.indexOf(';', closeIndex);
  if (semicolon < 0) throw new Error(`Missing semicolon after table ${tableName}.`);
  const body = source.slice(openIndex + 1, closeIndex);
  const tail = source.slice(closeIndex + 1, semicolon);
  const columns = [];
  const constraints = [];
  const indexes = [];
  const comments = [];
  const autoUpdateTables = new Set();

  for (const rawItem of splitItems(body)) {
    const item = rawItem.replace(/^\s*--.*$/gm, '').trim();
    if (!item) continue;
    if (/^(?:PRIMARY KEY|CONSTRAINT|FOREIGN KEY|CHECK)\b/i.test(item)) {
      constraints.push(item.replaceAll('`', ''));
      continue;
    }
    const indexMatch = item.match(/^(UNIQUE\s+)?(?:KEY|INDEX)\s+`?(\w+)`?\s*\(([^)]+)\)/i);
    if (indexMatch) {
      indexes.push({ unique: Boolean(indexMatch[1]), name: indexMatch[2], columns: indexMatch[3].replaceAll('`', '').trim() });
      continue;
    }

    const columnMatch = item.match(/^`?(\w+)`?\s+([\s\S]+)$/);
    if (!columnMatch) throw new Error(`Could not parse ${tableName} definition: ${item}`);
    const [, name, original] = columnMatch;
    let definition = original.replaceAll('`', '').trim();
    const commentMatch = definition.match(/\s+COMMENT\s+'((?:[^']|'')*)'\s*$/i);
    if (commentMatch) {
      comments.push(`COMMENT ON COLUMN ${tableName}.${name} IS ${quoteSql(commentMatch[1].replaceAll("''", "'"))};`);
      definition = definition.slice(0, commentMatch.index).trim();
    }

    const enumMatch = definition.match(/\bENUM\s*\(([^)]*)\)/i);
    if (enumMatch) {
      const values = readSqlStringList(enumMatch[1]);
      definition = definition.replace(enumMatch[0], 'TEXT');
      definition += ` CHECK (${name} IN (${values.join(', ')}))`;
    }
    const tinyBoolean = /\bTINYINT\s*\(\s*1\s*\)/i.test(definition);
    definition = definition.replace(/\bTINYINT\s*\(\s*1\s*\)/gi, 'SMALLINT').replace(/\bTINYINT\b/gi, 'SMALLINT');
    if (tinyBoolean) definition += ` CHECK (${name} IN (0, 1))`;
    definition = definition.replace(/\bMEDIUMTEXT\b/gi, 'TEXT').replace(/\bLONGTEXT\b/gi, 'TEXT');
    definition = definition.replace(/\bTIMESTAMP\b/gi, 'TIMESTAMPTZ');
    definition = definition.replace(/\bBIGINT\s+PRIMARY KEY\s+AUTO_INCREMENT\b/i, 'BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY');
    definition = definition.replace(/\bON UPDATE CURRENT_TIMESTAMP(?:\(\))?/gi, '');
    if (/\bupdated_at\b/i.test(name) && /CURRENT_TIMESTAMP/i.test(original)) autoUpdateTables.add(tableName);
    columns.push(`  ${name} ${definition.replace(/\s+/g, ' ').trim()}`);
  }

  const tableCommentMatch = tail.match(/COMMENT\s*=\s*'((?:[^']|'')*)'/i);
  if (tableCommentMatch) comments.unshift(`COMMENT ON TABLE ${tableName} IS ${quoteSql(tableCommentMatch[1].replaceAll("''", "'"))};`);
  tables.push({ name: tableName, columns, constraints, indexes, comments, autoUpdate: autoUpdateTables.has(tableName) });
  lastEnd = semicolon + 1;
  tableStartPattern.lastIndex = lastEnd;
}
seeds.push(...source.slice(lastEnd).split(';').map((sql) => sql.trim()).filter(Boolean));

const schemaParts = [];
for (const table of tables) {
  schemaParts.push(`CREATE TABLE IF NOT EXISTS ${table.name} (\n${[...table.columns, ...table.constraints.map((line) => `  ${line}`)].join(',\n')}\n);`);
}
for (const table of tables) {
  for (const index of table.indexes) {
    schemaParts.push(`CREATE ${index.unique ? 'UNIQUE ' : ''}INDEX IF NOT EXISTS ${index.name} ON ${table.name} (${index.columns});`);
  }
  schemaParts.push(...table.comments);
}
const autoUpdateTables = tables.filter((table) => table.autoUpdate);
if (autoUpdateTables.length) {
  schemaParts.push(`CREATE OR REPLACE FUNCTION set_updated_at() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  NEW.updated_at = now();
  RETURN NEW;
END;
$$;`);
  for (const table of autoUpdateTables) {
    schemaParts.push(`DROP TRIGGER IF EXISTS trg_${table.name}_updated_at ON ${table.name};\nCREATE TRIGGER trg_${table.name}_updated_at BEFORE UPDATE ON ${table.name} FOR EACH ROW EXECUTE FUNCTION set_updated_at();`);
  }
}

const seedSql = seeds
  .map((sql) => sql.replace(/^\s*--.*$/gm, '').trim())
  .filter((sql) => sql && !/^CREATE DATABASE\b|^USE\b/i.test(sql))
  .map((sql) => sql.replace(/^INSERT\s+IGNORE\s+INTO/i, 'INSERT INTO').replace(/;?\s*$/g, '') + ' ON CONFLICT DO NOTHING;')
  .join('\n\n');
const output = path.join(root, 'database', 'postgres');
await mkdir(output, { recursive: true });
await writeFile(path.join(output, 'schema.sql'), `${schemaParts.join('\n\n')}\n`, 'utf8');
await writeFile(path.join(output, 'seed.sql'), `${seedSql}\n`, 'utf8');
console.log(`Generated ${tables.length} PostgreSQL tables and ${seeds.length} seed statements.`);
