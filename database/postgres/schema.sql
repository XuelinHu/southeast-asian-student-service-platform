CREATE TABLE IF NOT EXISTS roles (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code VARCHAR(32) NOT NULL UNIQUE,
  name VARCHAR(60) NOT NULL,
  scope TEXT NOT NULL CHECK (scope IN ('user', 'staff')),
  data_scope TEXT NOT NULL DEFAULT 'self' CHECK (data_scope IN ('self', 'class', 'all')),
  description VARCHAR(255) NULL,
  is_super SMALLINT NOT NULL DEFAULT 0 CHECK (is_super IN (0, 1)),
  is_builtin SMALLINT NOT NULL DEFAULT 0 CHECK (is_builtin IN (0, 1)),
  status TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'disabled')),
  sort_order INT NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS role_menus (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  role_id BIGINT NOT NULL,
  menu_key VARCHAR(64) NOT NULL,
  can_view SMALLINT NOT NULL DEFAULT 1 CHECK (can_view IN (0, 1)),
  can_create SMALLINT NOT NULL DEFAULT 0 CHECK (can_create IN (0, 1)),
  can_update SMALLINT NOT NULL DEFAULT 0 CHECK (can_update IN (0, 1)),
  can_delete SMALLINT NOT NULL DEFAULT 0 CHECK (can_delete IN (0, 1)),
  teacher_types VARCHAR(120) NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_role_menus_role FOREIGN KEY (role_id) REFERENCES roles(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username VARCHAR(64) NOT NULL UNIQUE,
  password_hash VARCHAR(255) NOT NULL,
  role_id BIGINT NOT NULL,
  display_name VARCHAR(120) NOT NULL,
  email VARCHAR(120) NULL,
  phone VARCHAR(40) NULL,
  status TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'disabled')),
  remark VARCHAR(255) NULL,
  last_login_at TIMESTAMPTZ NULL,
  token_version INT NOT NULL DEFAULT 0,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_users_role FOREIGN KEY (role_id) REFERENCES roles(id)
);

CREATE TABLE IF NOT EXISTS nationalities (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  country_code VARCHAR(8) NOT NULL UNIQUE,
  name_zh VARCHAR(120) NOT NULL,
  name_en VARCHAR(120) NOT NULL,
  continent VARCHAR(60),
  primary_language VARCHAR(80),
  timezone VARCHAR(80),
  status TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'disabled')),
  sort_order INT NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS teachers (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT UNIQUE,
  teacher_no VARCHAR(64) NOT NULL UNIQUE,
  name VARCHAR(120) NOT NULL,
  college VARCHAR(120),
  phone VARCHAR(40),
  email VARCHAR(120),
  teacher_type TEXT NOT NULL DEFAULT 'course_teacher' CHECK (teacher_type IN ('course_teacher', 'head_teacher', 'counselor', 'admin_teacher')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_teachers_user FOREIGN KEY (user_id) REFERENCES users(id)
);

CREATE TABLE IF NOT EXISTS classes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code VARCHAR(64) NOT NULL UNIQUE,
  name VARCHAR(120) NOT NULL,
  college VARCHAR(120),
  major VARCHAR(120),
  teacher_id BIGINT,
  enrollment_year INT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_classes_teacher FOREIGN KEY (teacher_id) REFERENCES teachers(id)
);

CREATE TABLE IF NOT EXISTS students (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT UNIQUE,
  student_no VARCHAR(64) NOT NULL UNIQUE,
  chinese_name VARCHAR(120),
  english_name VARCHAR(120) NOT NULL,
  gender VARCHAR(20),
  birth_date DATE,
  nationality_id BIGINT,
  passport_no VARCHAR(80),
  passport_expiry DATE,
  phone VARCHAR(40),
  email VARCHAR(120),
  emergency_contact VARCHAR(160),
  enrollment_year INT,
  major VARCHAR(120),
  college VARCHAR(120),
  class_id BIGINT,
  status TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'suspended', 'withdrawn', 'graduated', 'delayed')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_students_user FOREIGN KEY (user_id) REFERENCES users(id),
  CONSTRAINT fk_students_nationality FOREIGN KEY (nationality_id) REFERENCES nationalities(id),
  CONSTRAINT fk_students_class FOREIGN KEY (class_id) REFERENCES classes(id)
);

CREATE TABLE IF NOT EXISTS dormitories (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  building VARCHAR(120) NOT NULL,
  room_no VARCHAR(60) NOT NULL,
  bed_no VARCHAR(60) NOT NULL,
  student_id BIGINT,
  check_in_date DATE,
  check_out_date DATE,
  status TEXT NOT NULL DEFAULT 'available' CHECK (status IN ('available', 'occupied', 'reserved', 'maintenance')),
  CONSTRAINT fk_dormitories_student FOREIGN KEY (student_id) REFERENCES students(id)
);

CREATE TABLE IF NOT EXISTS visas (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  student_id BIGINT NOT NULL,
  visa_type VARCHAR(80) NOT NULL,
  visa_no VARCHAR(120),
  issue_date DATE,
  expiry_date DATE NOT NULL,
  residence_permit_no VARCHAR(120),
  document_url VARCHAR(255),
  status TEXT NOT NULL DEFAULT 'valid' CHECK (status IN ('valid', 'expiring', 'expired', 'renewing')),
  CONSTRAINT fk_visas_student FOREIGN KEY (student_id) REFERENCES students(id)
);

CREATE TABLE IF NOT EXISTS study_records (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  student_id BIGINT NOT NULL,
  course_code VARCHAR(80),
  course_name VARCHAR(160) NOT NULL,
  attendance_rate DECIMAL(5,2),
  homework_status VARCHAR(120),
  class_performance VARCHAR(255),
  warning_level TEXT NOT NULL DEFAULT 'none' CHECK (warning_level IN ('none', 'notice', 'warning', 'serious')),
  teacher_id BIGINT,
  recorded_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_study_records_student FOREIGN KEY (student_id) REFERENCES students(id),
  CONSTRAINT fk_study_records_teacher FOREIGN KEY (teacher_id) REFERENCES teachers(id)
);

CREATE TABLE IF NOT EXISTS external_schools (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  country_code VARCHAR(8),
  name VARCHAR(180) NOT NULL,
  contact_name VARCHAR(120),
  contact_email VARCHAR(120),
  integration_type TEXT NOT NULL DEFAULT 'manual' CHECK (integration_type IN ('api', 'excel', 'csv', 'manual', 'scheduled_sync')),
  endpoint_url VARCHAR(255),
  status TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'disabled'))
);

CREATE TABLE IF NOT EXISTS grade_rules (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  school_id BIGINT,
  country_code VARCHAR(8),
  name VARCHAR(160) NOT NULL,
  version VARCHAR(40) NOT NULL,
  gpa_scale DECIMAL(4,2) NOT NULL DEFAULT 4.00,
  credit_ratio DECIMAL(6,3) NOT NULL DEFAULT 1.000,
  pass_score DECIMAL(5,2) NOT NULL DEFAULT 60.00,
  status TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'disabled')),
  effective_from DATE,
  effective_to DATE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_grade_rules_school FOREIGN KEY (school_id) REFERENCES external_schools(id)
);

CREATE TABLE IF NOT EXISTS grade_records (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  student_id BIGINT NOT NULL,
  course_code VARCHAR(80),
  course_name VARCHAR(160),
  source_school_id BIGINT,
  source_country_code VARCHAR(8),
  original_grade VARCHAR(40),
  original_type TEXT CHECK (original_type IN ('percent', 'letter', 'gpa', 'pass_fail')),
  original_credit DECIMAL(6,2) DEFAULT 0,
  adapted_score DECIMAL(5,2),
  adapted_gpa DECIMAL(4,2),
  adapted_credit DECIMAL(6,2),
  passed SMALLINT CHECK (passed IN (0, 1)),
  rule_version VARCHAR(40),
  adapt_status TEXT NOT NULL DEFAULT 'pending' CHECK (adapt_status IN ('pending', 'success', 'exception')),
  exception_reason VARCHAR(255),
  audit_status TEXT NOT NULL DEFAULT 'pending' CHECK (audit_status IN ('pending', 'approved', 'rejected', 'archived')),
  audited_by BIGINT,
  audited_at TIMESTAMPTZ NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_grade_records_student FOREIGN KEY (student_id) REFERENCES students(id),
  CONSTRAINT fk_grade_records_school FOREIGN KEY (source_school_id) REFERENCES external_schools(id),
  CONSTRAINT fk_grade_records_auditor FOREIGN KEY (audited_by) REFERENCES users(id)
);

CREATE TABLE IF NOT EXISTS login_logs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NULL,
